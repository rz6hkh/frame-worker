"""Правила альбомов - единственный файл, который правится словами.

Здесь пример. Настоящие правила у каждого свои и живут рядом,
в `rules.py`, который не публикуется: в них видно, кого я считаю
близкими и какие кадры не показываю гостям. Механизм от содержания не
зависит, поэтому для понимания устройства примера достаточно.

Каждое правило получает снимок `p` и отвечает True, если он подходит:

    p.types        типы людей в кадре, например ["близкие", "коллеги"]
    p.f            признаки: категория и флаги от модели, метрики резкости
                   и яркости, число кусков текста от OCR, снят ли камерой
    p.year, p.city из EXIF

До правил, ко всем альбомам одинаково, вычитается: то, что уже лежит в
альбоме-мусорке, люди с типом «не показывать» и `junk`.
"""


def count(p, t):
    return sum(1 for x in p.types if x == t)


def has(p, *types):
    return any(count(p, t) > 0 for t in types)


def screenshot(f):
    """Скриншот, которого не разглядела модель: объявление, переписка, реклама.

    OCR нашёл много кусков текста, а EXIF камеры нет. Пороги подобраны
    замером: у снимков, названных моделью скриншотами, медиана 21 кусок и
    90% имеют не меньше пяти; у обычных фотографий медиана ноль и таких 2%.
    Условие «снято камерой» спасает настоящие кадры с текстом - приборные
    панели, вывески, таблички.
    """
    if not f:
        return False
    return (f.get("ocr") or 0) >= 5 and not f.get("cam")


def junk(f):
    """Однозначный брак. Метрики читаются только если они посчитаны."""
    if not f:
        return False
    if screenshot(f):
        return True
    if f.get("sd") is not None:
        if f["sd"] < 10 and f["mean"] < 10:          # чёрный кадр
            return True
        if f["dark"] > 0.97 and f["sd"] < 12:        # тёмный провал
            return True
        if f["bright"] > 0.9 and f["mean"] > 240:    # пересвет
            return True
    return f.get("category") in ("junk", "screenshot", "document")


def sensitive(f):
    """Признак «не всем». Что именно считать таким - дело того, чей это архив.

    В настоящих правилах здесь несколько градаций от модели и разные
    альбомы вычитают разные из них: свой круг терпимее, чем показ гостям.
    """
    return bool(f) and bool(f.get("sensitive"))


RULES = {
    # Свой круг: строгих вычетов нет.
    "Близкие": lambda p: has(p, "близкие"),

    # Те же люди, но для показа при посторонних.
    "Гостям": lambda p: has(p, "близкие") and not sensitive(p.f),

    # Без людей: пейзажи и животные по разметке модели.
    "Красивое": lambda p: not p.types and p.f and p.f.get("category") in ("travel", "animals"),

    # Один предмет как главный герой кадра.
    "Техника": lambda p: p.f and p.f.get("category") == "cars",
}
